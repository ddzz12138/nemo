import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, rm, readFile, symlink } from 'node:fs/promises';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { gunzipSync } from 'node:zlib';
import { releaseEntries, packageRelease } from '../lib/release.mjs';

test('release allowlist excludes runtime data, logs, coordination and private screenshots',async t=>{
  const root=await mkdtemp(join(tmpdir(),'nemo-release-'));t.after(()=>rm(root,{recursive:true,force:true}));
  for(const name of ['lib','public','bin','docs','desktop','references','scripts','.nemo','.work','coordination'])await mkdir(join(root,name));
  for(const name of ['package-lock.json','server.mjs','mcp-server.mjs','remote-service.mjs','LICENSE','README.md','QUICKSTART.md','CONTRIBUTING.md','SECURITY.md','THIRD_PARTY_NOTICES.md'])await writeFile(join(root,name),'Synthetic source');
  await writeFile(join(root,'package.json'),JSON.stringify({name:'nemo-fixture',version:'1.0.0'}));
  await writeFile(join(root,'lib','secrets.mjs'),'export const safe = true;');
  await writeFile(join(root,'references','hermes-memory-LICENSE.txt'),'Synthetic license');
  await writeFile(join(root,'references','private-image.png'),'PRIVATE_IMAGE');
  await writeFile(join(root,'scripts','check-syntax.mjs'),'// syntax');await writeFile(join(root,'scripts','package-release.mjs'),'// package');await writeFile(join(root,'scripts','connect-gmail.mjs'),'// connect');
  for(const name of ['setup-gmail-web.mjs','prepare-phone-assets.mjs','export-phone-app.mjs'])await writeFile(join(root,'scripts',name),'// synthetic operator helper');
  await mkdir(join(root,'deploy','phone-relay'),{recursive:true});await writeFile(join(root,'deploy','phone-relay','coturn.conf.example'),'# synthetic relay template');
  await writeFile(join(root,'.nemo','state.json'),'PRIVATE_CHAT');await writeFile(join(root,'coordination','report.md'),'PRIVATE_REPORT');
  const entries=await releaseEntries(root);assert.ok(entries.some(entry=>entry.name==='lib/secrets.mjs'));assert.ok(!JSON.stringify(entries).includes('PRIVATE'));
  assert.ok(entries.some(entry=>entry.name==='scripts/export-phone-app.mjs'));assert.ok(entries.some(entry=>entry.name==='deploy/phone-relay/coturn.conf.example'));
  assert.ok(entries.some(entry=>entry.name==='scripts/setup-gmail-web.mjs'));
  const outDir=join(root,'.work','output'); const result=await packageRelease({root,outDir});
  const tar=gunzipSync(await readFile(join(outDir,result.name)));assert.ok(tar.includes(Buffer.from('package/package.json')));assert.ok(!tar.includes(Buffer.from('PRIVATE')));
  const again=await packageRelease({root,outDir});assert.equal(result.sha256,again.sha256);
  await mkdir(join(root,'desktop','interface','node_modules','synthetic-package'),{recursive:true});
  await writeFile(join(root,'desktop','interface','node_modules','.package-lock.json'),'GENERATED_DEPENDENCY');
  await writeFile(join(root,'desktop','interface','node_modules','synthetic-package','index.js'),'GENERATED_DEPENDENCY');
  const rebuilt=await packageRelease({root,outDir});
  assert.equal(rebuilt.sha256,result.sha256,'Normal frontend dependencies must not change the CLI archive.');
  await mkdir(join(root,'lib','__pycache__'));
  await writeFile(join(root,'lib','__pycache__','fixture.pyc'),'GENERATED_PRIVATE_BUILD_PATH');
  assert.equal((await packageRelease({root,outDir})).sha256,result.sha256,'Generated Python cache bytes must never enter the source archive.');
  assert.ok(!(await releaseEntries(root)).some(entry=>entry.name.includes('node_modules')));
  assert.ok(!gunzipSync(await readFile(join(outDir,rebuilt.name))).includes(Buffer.from('GENERATED_DEPENDENCY')));
  await writeFile(join(root,'desktop','interface','gmail-tokens.dpapi'),'DO_NOT_SHIP');
  await assert.rejects(releaseEntries(root),/Private/);
  await rm(join(root,'desktop','interface','gmail-tokens.dpapi'));
  const generated=join(root,'desktop','interface','node_modules');
  await rm(generated,{recursive:true,force:true});
  await writeFile(generated,'A file is not a generated dependency directory.');
  await assert.rejects(releaseEntries(root),/regular generated directory/);
  await rm(generated);
  await symlink(join(root,'.work'),generated,process.platform==='win32'?'junction':'dir');
  await assert.rejects(releaseEntries(root),/regular generated directory/);
  await rm(generated,{recursive:true,force:true});
  await symlink(join(root,'.work'),join(root,'lib','linked'),process.platform==='win32'?'junction':'dir');
  await assert.rejects(releaseEntries(root),/symlinks/);
  await rm(join(root,'lib','linked'),{recursive:true,force:true});
  await writeFile(join(root,'lib','gmail-tokens.dpapi'),'DO_NOT_SHIP');await assert.rejects(releaseEntries(root),/Private/);
});
